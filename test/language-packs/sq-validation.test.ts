import { describe, expect, it } from 'vitest';
import { resolveSelection } from '../../packages/repository-linguistics/src';
import { sqAdapter } from '../../src/adapters/sq';
import { MIN_VALIDATION_CASES, SQ_VALIDATION, albanianManifest, readSelection, runCase } from '../../packages/language-packs/src';

describe('the Albanian validation cases against the real adapter', () => {
  const m = albanianManifest();

  it('has at least the required number of real selections', () => {
    expect(m.validation.length).toBeGreaterThanOrEqual(MIN_VALIDATION_CASES);
    expect(m.validation).toEqual(SQ_VALIDATION);
    expect(m.validation).not.toBe(SQ_VALIDATION); // a caller may edit its copy without changing the pack
  });

  for (const c of SQ_VALIDATION) {
    it(`${c.id}: ${c.surface}${c.sentence ? ` in “${c.sentence}”` : ''}`, () => {
      const r = runCase(sqAdapter, c);
      expect(r.got, r.got).toBeUndefined();
      expect(r.pass).toBe(true);
    });
  }

  it('the document of record: librin is libër NOUN accusative definite singular', () => {
    const r = readSelection(sqAdapter, 'librin', 'Fëmijët lexojnë librin.');
    expect(r.top).toMatchObject({ lemma: 'libër', pos: 'NOUN', morph: { Case: 'Acc', Definite: 'Def', Number: 'Sing' } });
  });

  it('a form generated by the rules is provisional, a hand-listed form high-confidence, close readings conflicted', () => {
    expect(readSelection(sqAdapter, 'çajin', 'Nëna pi çajin.').status).toBe('provisional');
    expect(readSelection(sqAdapter, 'shkollë', 'Ana shkon në shkollë.').status).toBe('high-confidence');
    expect(readSelection(sqAdapter, 'Nëna', 'Nëna pi çajin.').status).toBe('conflicted');
    expect(readSelection(sqAdapter, 'jetë', 'Ana ka një jetë të mirë.').status).toBe('conflicted');
  });

  it('an unknown word gets no reading and is provisional', () => {
    const r = readSelection(sqAdapter, 'Xyzqwk', 'Xyzqwk është këtu.');
    expect(r.candidates).toEqual([]);
    expect(r.status).toBe('provisional');
  });

  it('the pack’s status rule agrees with the Repository resolver on every case', () => {
    for (const c of SQ_VALIDATION) {
      const text = c.sentence ?? c.surface;
      const at = text.indexOf(c.surface);
      const repo = resolveSelection({ languageId: 'sq', surface: c.surface, sentence: c.sentence, selStart: at, selEnd: at + c.surface.length, now: '2026-10-08T00:00:00Z' });
      expect(readSelection(sqAdapter, c.surface, c.sentence).status, c.id).toBe(repo.analysis.status);
    }
  });

  it('reports a failing expectation with what the adapter really read, instead of hiding it', () => {
    const r = runCase(sqAdapter, { id: 'wrong', surface: 'librin', sentence: 'Fëmijët lexojnë librin.', expect: { lemma: 'shtëpi', features: { Case: 'Nom' } } });
    expect(r.pass).toBe(false);
    expect(r.got).toContain('libër');
    expect(r.got).toContain('lemma libër');
    expect(r.got).toContain('Case=Acc');
  });

  it('reports a surface that is not in the sentence', () => {
    const r = runCase(sqAdapter, { id: 'absent', surface: 'tavolinë', sentence: 'Fëmijët lexojnë librin.', expect: { lemma: 'tavolinë' } });
    expect(r.pass).toBe(false);
    expect(r.got).toContain('not found');
  });

  it('the manifest’s capabilities come from the adapter’s own support levels', () => {
    expect(m.analyzer.capabilities).toEqual(expect.arrayContaining(['lemma', 'morphology', 'phrases', 'pronunciation-notes']));
    expect(sqAdapter.support.lemmatization).not.toBe('none');
  });
});
