/**
 * The crypto dependencies of the in-process service on a device: no Node, no scrypt, no password.
 *
 * `CryptoPort.sha256` is synchronous (the handler hashes a bearer token inside a request and a sentence while it resolves a
 * lookup), and `crypto.subtle.digest` is asynchronous, so SHA-256 is computed here in plain JavaScript (FIPS 180-4; the tests
 * compare it with Node's). Randomness comes from `crypto.getRandomValues` and `crypto.randomUUID`, which every browser
 * and service worker has. The local account has no password: `hashPassword` refuses and `verifyPassword` is always false, so
 * the in-process `/accounts` and `/sessions` routes cannot be used to sign in here (the local session is made by the package).
 */
