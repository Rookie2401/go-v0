/** The generated paradigm of a lemma for one standard, or undefined (an unknown lemma; a part of speech that does not inflect). */
export function norwegianParadigm(std: NoStandard, lemma: string, pos: PartOfSpeech): GeneratedParadigm | undefined {
  const lex = lexiconFor(std);
  switch (pos) {
    case 'NOUN': return nounParadigm(lex, std, lemma);
    case 'ADJ': return adjectiveParadigm(lex, std, lemma);
    case 'VERB': return verbParadigm(lex, std, lemma);
    case 'AUX': return auxParadigm(lex, std, lemma) ?? verbParadigm(lex, std, lemma);
    case 'PRON': return closedParadigm(lex, std, lemma, 'PRON');
    case 'DET': return closedParadigm(lex, std, lemma, 'DET');
    default: return undefined;
  }
}
