import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { beforeAll, describe, expect, it } from 'vitest';
import { createMemoryStore } from '../../src/core';
import { importDocuments, type CorpusDocument } from '../../src/ingest';
import {
  CASES, Recorder, formatTable, renderProof, runProof, sameCodePoints, snapshotStore, type ProofResult,
} from '../../scripts/corpus-prove-lib.mts';
import { baseDoc, clock, registry, warningCodes } from './helpers';

const DIR = 'data/synthetic/import-proof';
const MARK = 'SYNTHETIC DEVELOPMENT MATERIAL for import testing — not learner content';

describe('corpus:prove — the proof cases run in the gate', () => {
  let result: ProofResult;
  beforeAll(async () => { result = await runProof(); }, 400_000);

  it('every check of every case matches (expected == actual)', () => {
    const failed = result.rows.filter((x) => !x.ok);
    expect(failed, formatTable(result)).toEqual([]);
    expect(result.ok).toBe(true);
    expect(result.rows.length).toBeGreaterThan(130);
  });

  it.each(CASES.map((k) => k.id))('case %s has checks and none fail', (id) => {
    const rows = result.rows.filter((x) => x.caseId === id);
    expect(rows.length).toBeGreaterThan(0);
    expect(rows.filter((x) => !x.ok)).toEqual([]);
  });

  it('covers every case the plan names', () => {
    const text = CASES.map((k) => `${k.id} ${k.title}`).join('\n');
    for (const needle of ['valid', 'learner', 'unchanged', 'malformed', 'missing', 'duplicate', 'mixed', 'spans', 'alignment', 'exactness', 'holds', 'revision', 'operating', 'bundled']) {
      expect(text, needle).toContain(needle);
    }
  });

  it('the rejected cases wrote zero rows to every table and gave actionable hints', () => {
    const writes = result.rows.filter((x) => /rows written$/.test(x.check));
    expect(writes.length).toBe(10);
    for (const w of writes) { expect(w.ok, w.check).toBe(true); expect(w.actual, w.check).toMatch(/^0 rows \(\d+ rows before and after, \d+ tables identical\)$/); }
    const hints = result.rows.filter((x) => /actionable hint$/.test(x.check));
    expect(hints.length).toBe(writes.length);
  });

  it('PROOF.md is rendered from the rows of the run, nothing else', () => {
    const doc = renderProof(result, { command: 'npm run corpus:prove -- --write', date: '2026-09-30', node: 'test' });
    expect(doc).toContain('GENERATED by `npm run corpus:prove -- --write`');
    expect(doc).toContain('ALL MATCH');
    expect(doc).not.toContain('MISMATCH**');
    const tableRows = doc.split('\n').filter((l) => /^\| \d\d /.test(l) && / \| (match|\*\*MISMATCH\*\*) \|$/.test(l));
    expect(tableRows.length).toBe(result.rows.length);
    expect(doc).toContain(`${result.rows.length} checks`);
  });

  it('the committed docs/import/PROOF.md (if present) says ALL MATCH and was generated, not hand-written', () => {
    const p = 'docs/import/PROOF.md';
    if (!fs.existsSync(p)) return;
    const doc = fs.readFileSync(p, 'utf8');
    expect(doc).toContain('GENERATED by `npm run corpus:prove -- --write`');
    expect(doc).toContain('**ALL MATCH**');
    expect(doc).not.toContain('**MISMATCH**');
  });
});

describe('the proof can fail', () => {
  it('sameCodePoints tells composed from decomposed text and NBSP from a space', () => {
    expect(sameCodePoints('niño', 'niño')).toBe(true);
    expect(sameCodePoints('niño', 'niño')).toBe(false);
    expect(sameCodePoints('a b', 'a b')).toBe(false);
    expect(sameCodePoints(' a', 'a')).toBe(false);
  });

  it('the recorder marks a difference as a mismatch', () => {
    const r = new Recorder();
    r.eq('x', 'same', { a: 1 }, { a: 1 });
    r.eq('x', 'different', 6, 5);
    r.that('x', 'words', 'yes', 'no', false);
    expect(r.rows.map((x) => x.ok)).toEqual([true, false, false]);
  });

  it('a tampered synthetic file turns the proof red (so a green proof means something)', async () => {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'go-prove-tamper-'));
    try {
      fs.cpSync(DIR, tmp, { recursive: true });
      const p = path.join(tmp, '01-valid-es.json');
      const doc = JSON.parse(fs.readFileSync(p, 'utf8')) as CorpusDocument;
      (doc.sections[0].paragraphs[0] as { sentences: unknown[] }).sentences.pop(); // five sentences instead of six
      fs.writeFileSync(p, JSON.stringify(doc), 'utf8');
      const red = await runProof({ dir: tmp, cli: false });
      expect(red.ok).toBe(false);
      expect(red.rows.some((x) => !x.ok && x.caseId === '01 valid-text')).toBe(true);
    } finally { fs.rmSync(tmp, { recursive: true, force: true }); }
  }, 120_000);
});

describe('the synthetic material is clearly identified and kept apart', () => {
  const files = fs.readdirSync(DIR).filter((f) => f.endsWith('.json')).sort();

  it('has one file per case of the plan', () => {
    expect(files).toEqual([
      '01-valid-es.json', '02-malformed.json', '03-missing-fields.json', '04-duplicate-id-a.json', '04-duplicate-id-b.json',
      '05-batch-invalid.json', '05-batch-valid.json', '06-spans-grapheme-es.json', '06-spans-grapheme-hi.json', '06-spans-out-of-bounds.json',
      '06-spans-overlap.json', '07-alignment-broken.json', '08-exact-es.json', '08-exact-hi-danda.json', '08-exact-th-no-spaces.json',
      '09-valid-es-revised.json', '10-hold-review.json', '10-hold-rights.json', '10-scripture-generated.json', '10-scripture-unverified.json',
    ]);
  });

  it('every file says it is synthetic; every id starts with synthetic-', () => {
    for (const f of files) {
      const raw = fs.readFileSync(path.join(DIR, f), 'utf8');
      expect(raw, f).toContain(MARK.split(' — ')[0]);
      let doc: CorpusDocument | undefined;
      try { doc = JSON.parse(raw) as CorpusDocument; } catch { doc = undefined; }
      if (f === '02-malformed.json') { expect(doc, f).toBeUndefined(); continue; }
      expect(doc, f).toBeDefined();
      const d = doc!;
      expect(d.id, f).toMatch(/^synthetic-/);
      expect(d.source.id, f).toMatch(/^synthetic-/);
      expect(d.corpus.id, f).toMatch(/^synthetic-/);
      expect(d.source.provenance ?? '', f).toContain(MARK);
      if (f === '03-missing-fields.json') continue; // deliberately lacks generated and review
      if (f !== '10-scripture-unverified.json') expect(d.generated, f).toBe(true); // Scripture cannot be generated: that is its own case
      if (f !== '10-hold-rights.json' && f !== '10-scripture-unverified.json') expect(d.review.status, f).toBe('unreviewed');
    }
  });

  it('Scripture-shaped files carry only the placeholder wording', () => {
    for (const f of ['10-scripture-unverified.json', '10-scripture-generated.json']) {
      const d = JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8')) as CorpusDocument;
      const texts = d.sections.flatMap((s) => s.paragraphs.flatMap((p) => ('sentences' in p ? p.sentences.map((x) => x.text) : [p.text])));
      expect(texts.length).toBeGreaterThan(0);
      for (const t of texts) expect(t, f).toMatch(/^PLACEHOLDER — not Scripture/);
    }
  });

  it('the folder README says it is synthetic and never bundled; nothing here is under data/corpus', () => {
    const readme = fs.readFileSync(path.join(DIR, 'README.md'), 'utf8');
    expect(readme).toContain(MARK);
    expect(readme).toMatch(/never bundled/);
    expect(path.resolve(DIR).includes(`${path.sep}corpus${path.sep}`)).toBe(false);
  });
});

describe('regression found by the proof: a raw paragraph with edge whitespace is warned about, and kept exactly', () => {
  const raw = '  Hola. Gracias.  ';
  it('validate warns (edge-whitespace) like it does for a declared sentence', () => {
    const d = baseDoc();
    d.sections = [{ paragraphs: [{ text: raw }] }];
    expect(warningCodes(d)).toContain('edge-whitespace');
    const clean = baseDoc();
    clean.sections = [{ paragraphs: [{ text: 'Hola. Gracias.' }] }];
    expect(warningCodes(clean)).not.toContain('edge-whitespace');
  });

  it('the stored paragraph is byte-identical and every sentence slices it', async () => {
    const d = baseDoc();
    d.sections = [{ paragraphs: [{ text: raw }] }];
    const store = createMemoryStore();
    const report = await importDocuments(store, registry, [d], { clock });
    expect(report.documents[0].issues.some((i) => i.code === 'edge-whitespace' && i.path === 'sections[0].paragraphs[0].text')).toBe(true);
    const [p] = await store.paragraphs.all();
    expect(sameCodePoints(p.originalText ?? '', raw)).toBe(true);
    for (const s of await store.sentences.all()) expect((p.originalText ?? '').slice(s.paraStart, s.paraEnd)).toBe(s.text);
    expect((await snapshotStore(store)).total).toBeGreaterThan(0);
  });
});
