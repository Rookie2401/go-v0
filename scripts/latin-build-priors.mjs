#!/usr/bin/env node
/**
 * Builds src/adapters/latin/priors-data.ts: for the commonest written forms, which (lemma, part of speech) the Latin treebanks
 * read them as. The analyser uses it ONLY to order the readings it already has (a boost on a reading that matches), never to add one.
 *
 * Training data: the Perseus Latin Dependency Treebank files of texts that are NOT among the evaluation corpora (docs/latin/EVAL.md):
 * Caesar (BG 7), Sallust, Tacitus (Annals), Petronius, Phaedrus, Suetonius (Divus Augustus), Propertius, Res Gestae. The treebanks
 * the analyser is scored against (the PROIEL New Testament, the Perseus Cicero, Vergil, Ovid and Jerome) are never read here, so the
 * published accuracy is measured on text the priors have not seen.
 * Perseus Latin treebank: CC BY-SA 3.0 (Perseus Digital Library, Tufts).
 *
 * Reads C:/Users/CJWal/dev/latin-eval-sources/perseus (downloaded by the evaluation lane). Usage: node scripts/latin-build-priors.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, '..', 'src', 'adapters', 'latin', 'priors-data.ts');
const DIR = process.env.LATIN_EVAL_SOURCES ? path.join(process.env.LATIN_EVAL_SOURCES, 'perseus') : 'C:/Users/CJWal/dev/latin-eval-sources/perseus';
const TRAIN = ['phi0448.phi001', 'phi0631.phi001', 'phi1351.phi005', 'phi0972.phi001', 'phi0975.phi001', 'phi1348.abo012', 'phi0620.phi001', 'phi1221.phi007'];
const GROUP = { n: 'N', v: 'V', t: 'V', a: 'A', d: 'D', c: 'C', r: 'R', p: 'P', m: 'M', i: 'I', e: 'I', g: 'D', l: 'P' };

const fold = (s) => s.normalize('NFD').replace(/\p{M}+/gu, '').normalize('NFC').toLowerCase().replace(/æ/g, 'ae').replace(/œ/g, 'oe').replace(/j/g, 'i').replace(/v/g, 'u');
const table = new Map();
let tokens = 0;
for (const file of fs.readdirSync(DIR)) {
  if (!TRAIN.some((t) => file.startsWith(t))) continue;
  const xml = fs.readFileSync(path.join(DIR, file), 'utf8');
  for (const m of xml.matchAll(/<word [^>]*>/g)) {
    const get = (k) => new RegExp(` ${k}="([^"]*)"`).exec(m[0])?.[1] ?? '';
    const form = get('form').replace(/&amp;/g, '&');
    const tag = get('postag');
    const lemma = get('lemma').replace(/[0-9]+$/, '');
    if (!tag || tag[0] === 'u' || !lemma || !/[A-Za-z]/.test(form) || /^-?(que|ne|ve)$/.test(form)) continue;
    const g = GROUP[tag[0]];
    if (!g) continue;
    const key = fold(form);
    const id = fold(lemma) + ':' + g;
    const e = table.get(key) ?? { total: 0, by: new Map() };
    e.total++;
    e.by.set(id, (e.by.get(id) ?? 0) + 1);
    table.set(key, e);
    tokens++;
  }
}
const rows = [...table.entries()].filter(([, e]) => e.total >= 2).sort((a, b) => b[1].total - a[1].total || (a[0] < b[0] ? -1 : 1)).slice(0, 9000);
const lines = rows.map(([key, e]) => {
  const top = [...e.by.entries()].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1)).slice(0, 3);
  return key + '\t' + e.total + '\t' + top.map(([id, n]) => `${id}:${n}`).join(' ');
});
const L = [];
L.push('/**');
L.push(' * GENERATED by scripts/latin-build-priors.mjs — do not edit by hand. For the commonest written forms: total occurrences in the training');
L.push(' * treebanks and the (lemma:group:count) readings seen. Training text: Perseus Latin Treebank (CC BY-SA 3.0) of Caesar, Sallust, Tacitus,');
L.push(' * Petronius, Phaedrus, Suetonius, Propertius and the Res Gestae, never of a text the analyser is scored on. Groups: N noun, V verb, A adjective,');
L.push(' * D adverb / particle, C conjunction, R preposition, P pronoun, M numeral, I interjection. Used only to order readings the analyser already has.');
L.push(' */');
L.push('export const FORM_PRIORS = ' + JSON.stringify(lines.join('\n')) + ';');
L.push('');
fs.writeFileSync(OUT, L.join('\n'));
console.error(`training tokens ${tokens}; forms kept ${rows.length}; ${(lines.join('\n').length / 1024).toFixed(0)} KB`);
