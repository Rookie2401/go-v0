L.push(' */');
L.push('export const GLOSS_LEAD: Record<string, string> = {');
for (const k of Object.keys(out).sort()) L.push(`  ${JSON.stringify(k)}: ${JSON.stringify(out[k])},`);
L.push('};');
L.push('');
fs.writeFileSync(OUT, L.join('\n'));
