/**
 * Norwegian paradigm generation (GoLearn Linguistic Engine V2, Stage 3), Bokmål (`nb`) and Nynorsk (`nn`): the forms a
 * lexeme takes, as the shared `GeneratedParadigm` shape of src/core/paradigm.ts, produced ONLY from what the engine's own
 * tables and rules generate: the noun, verb and adjective rows (`parseNounRows`, `parseVerbRows`, `parseAdjectiveRows`
 * with their plural / past / neuter rules) and the closed-class word list. Nothing here has a rule of its own.
 *
 * THE DICTIONARY HALF IS ABSENT. There is no Norwegian dictionary on disk (no kaikki file, no public/dict/nb shards), so
 * every cell is `generated` and every paradigm says so in its notes. `table-tags.ts` maps the kaikki tag vocabulary so
 * the merge (`mergeParadigm`) works the day the owner adds the dictionary (docs/norway/SPEC.md section 10).
 *
 * Cell shapes (docs/ecosystem/linguistics/PARADIGMS-nb-nn.md):
 *   noun        Definite (Ind, Def) x Number (Sing, Plur). Gender is a note, not a feature. A feminine Bokmål noun has two
 *               definite singulars (boka / boken): both are cells with the same features (the merge keeps the second as an
 *               alternative). Nynorsk differs only in what the rows generate (-ar masculine plurals, no boken).
 *   adjective   Degree Pos: indefinite singular 'Fem,Masc' (the common form; 'Fem' as its own cell only where the word list
 *               has a separate feminine, as lita), 'Neut', definite singular, plural. Degree Cmp, Degree Sup (Ind, Def).
 *   verb        infinitive; present; past; perfect participle (supine); imperative; the -s (nb) / -st (nn) passive. The
 *               perfect (har + participle), the future and modal use, and the bli-passive are CONSTRUCTIONS, not cells.
 *               The engine has no present participle (-ende), so there is no such cell.
 *   AUX         the same cells, from the word list (være, ha, bli, the modals).
 *   PRON / DET  the word list's forms with their Person, Number, Gender, Case, Definite (lemma-level PronType, Poss,
 *               Reflex are not features of a cell); only a lemma with at least two cells has a paradigm.
 *
 * What it will not do: a lemma outside the word list gets nothing, except a compound noun whose head the word list knows
 * (the engine's compound path, compounds.ts): its table is the head's with the front part added, says "guessed" in its
 * notes and is marked unconfirmed. Proper nouns, adverbs and the other uninflected classes have no paradigm.
 */
import type { GeneratedParadigm, ParadigmLayout, PartOfSpeech } from '../../core';
import { decomposeCompound } from './compounds';
import { lexiconFor, NB_NOUN_VARIANTS, type NoLexicon } from './lexicon';
import type { NoAdjective, NoNoun, NoStandard, NoVerb, NoWordForm } from './types';

type Features = Record<string, string>;
interface Cell { features: Features; form: string; note?: string }

const nfc = (s: string): string => s.normalize('NFC');
const lc = (s: string): string => nfc(s).toLocaleLowerCase('nb');
const STD_NAME: Record<NoStandard, string> = { nb: 'Bokmål', nn: 'Nynorsk' };
const NO_DICTIONARY = 'No Norwegian dictionary table has been imported yet (docs/norway/SPEC.md section 10), so every cell here is generated by the adapter\'s rules and word list and none can be marked verified or supported. All of it is machine-drafted and has not been checked by a native speaker or against Norsk ordbank.';

/** The construction ids (constructions.ts keys) a verb's table points to instead of cells. */
export const VERB_CONSTRUCTIONS: readonly string[] = ['perfect-har', 'modal-bare-infinitive', 'bli-passive'];

const split = (v: string | undefined): string[] => (v ? v.split(',').filter(Boolean) : []);

// ───────────────────────── analysis features -> cell features ─────────────────────────

/** Features of the word list that belong to the lemma, not to a cell (a layout section says which kind of word it is). */
const LEMMA_LEVEL = new Set(['PronType', 'Poss', 'Reflex', 'NumType', 'Polarity']);

/** The cell features of one closed-class word-list form (pronoun, determiner, a few adjectives). */
function closedCellFeatures(morph: Features): Features {
  const f: Features = {};
  for (const [k, v] of Object.entries(morph)) if (!LEMMA_LEVEL.has(k)) f[k] = v;
  // a possessive's Number is the thing owned: "Plur,Sing" on vår / vårt (the owner is plural, the thing is not)
  if (f.Number === 'Plur,Sing' && f.Gender) f.Number = 'Sing';
  if (f.Definite === 'Def' && !f.Number && f.Degree === 'Pos') f.Number = 'Sing';
  return f;
}

/**
 * The cell features an ANALYSED form can belong to: the analysis' union readings (Gender "Fem,Masc", Number "Plur,Sing",
 * Mood "Imp,Ind", VerbForm "Fin,Inf") taken apart into the cells they name. `[]` for a reading that is not a cell of the
 * table (a genitive -s, a compound's unconfirmed reading, a name). The tests use it to find the cell of any observed form.
 */
export function norwegianCellFeatures(pos: PartOfSpeech, morph: Features): Features[] {
  const out: Features[] = [];
  const push = (f: Features): void => { if (!out.some((o) => JSON.stringify(Object.entries(o).sort()) === JSON.stringify(Object.entries(f).sort()))) out.push(f); };
  if (morph.Case === 'Gen' && (pos === 'NOUN' || pos === 'PROPN')) return [];
  if (pos === 'NOUN') {
    for (const d of split(morph.Definite)) for (const n of split(morph.Number)) push({ Definite: d, Number: n });
    return out;
  }
  if (pos === 'ADJ') {
    const degree = split(morph.Degree);
    if (degree.includes('Cmp')) push({ Degree: 'Cmp' });
    if (degree.includes('Sup')) for (const d of split(morph.Definite)) push({ Degree: 'Sup', Definite: d });
    if (degree.includes('Pos') || !degree.length) {
      const nums = split(morph.Number);
      const defs = split(morph.Definite);
      if (morph.Gender && nums.includes('Sing') && defs.includes('Ind')) {
        // a union reading ("Fem,Masc,Neut": a neuter equal to the common form) is every cell it names
        const gs = split(morph.Gender);
        const options = new Set<string>([morph.Gender, ...gs]);
        if (gs.includes('Fem') && gs.includes('Masc')) options.add('Fem,Masc');
        for (const g of options) push({ Degree: 'Pos', Definite: 'Ind', Gender: g, Number: 'Sing' });
      }
      if (nums.includes('Plur')) push({ Degree: 'Pos', Number: 'Plur' });
      if (nums.includes('Sing') && defs.includes('Def')) push({ Degree: 'Pos', Definite: 'Def', Number: 'Sing' });
    }
    return out;
  }
  if (pos === 'VERB' || pos === 'AUX') {
    if (split(morph.Voice).includes('Pass')) return [{ Voice: 'Pass' }];
    const forms = split(morph.VerbForm);
    const tenses = split(morph.Tense);
    const moods = split(morph.Mood);
    const indicative = !moods.length || moods.includes('Ind');
    if (forms.includes('Inf')) push({ VerbForm: 'Inf' });
    if (moods.includes('Imp')) push({ VerbForm: 'Fin', Mood: 'Imp' });
    if (forms.includes('Fin') && indicative && tenses.includes('Pres')) push({ VerbForm: 'Fin', Mood: 'Ind', Tense: 'Pres' });
    if (forms.includes('Fin') && indicative && tenses.includes('Past')) push({ VerbForm: 'Fin', Mood: 'Ind', Tense: 'Past' });
    if (forms.includes('Part')) push({ VerbForm: 'Part', Tense: 'Past' });
    return out;
  }
  if (pos === 'PRON' || pos === 'DET') return [closedCellFeatures(morph)];
  return [];
}

// ───────────────────────── nouns ─────────────────────────

function nounLayout(): ParadigmLayout {
  return {
    columns: { key: 'Definite', values: [['Ind', 'indefinite (a, an)'], ['Def', 'definite (the, an ending)']] },
    rows: { key: 'Number', values: [['Sing', 'singular'], ['Plur', 'plural']] },
  };
}

const GENDER_WORD = { m: 'masculine (en)', f: 'feminine (ei)', n: 'neuter (et)' } as const;

function nounCells(n: NoNoun, std: NoStandard): { cells: Cell[]; notes: string[]; template: string } {
  const cells: Cell[] = [];
  const notes: string[] = [];
  const dfSg = n.defSg;
  if (!n.pluralOnly) {
    cells.push({ features: { Definite: 'Ind', Number: 'Sing' }, form: n.lemma });
    for (const d of dfSg) {
      const note = std === 'nb' && n.gender === 'f' ? (d.gender === 'Fem' ? `feminine: ${n.lemma === dfSg[0].form ? '' : 'ei '}${n.lemma}, ${d.form}` : `masculine: en ${n.lemma}, ${d.form} (also valid for a feminine noun)`) : undefined;
      cells.push({ features: { Definite: 'Def', Number: 'Sing' }, form: d.form, ...(note ? { note } : {}) });
    }
  }
  for (const p of n.plural) cells.push({ features: { Definite: 'Ind', Number: 'Plur' }, form: p, ...(p === n.lemma && !n.pluralOnly ? { note: 'same as the singular (a zero plural)' } : {}) });
  for (const p of n.defPl) cells.push({ features: { Definite: 'Def', Number: 'Plur' }, form: p });
  const variant = std === 'nb' ? NB_NOUN_VARIANTS[n.lemma] : undefined;
  if (variant) {
    const note = `variant spelling (${n.lemma} and ${variant.indef[0]} are one word)`;
    for (const f of variant.indef) cells.push({ features: { Definite: 'Ind', Number: 'Sing' }, form: f, note });
    for (const f of variant.defSg) cells.push({ features: { Definite: 'Def', Number: 'Sing' }, form: f, note });
    for (const f of variant.pl) cells.push({ features: { Definite: 'Ind', Number: 'Plur' }, form: f, note });
    for (const f of variant.defPl) cells.push({ features: { Definite: 'Def', Number: 'Plur' }, form: f, note });
  }

  const std2 = STD_NAME[std];
  if (n.pluralOnly) notes.push(`Plural only: ${n.lemma} has no singular.`);
  else if (n.massNoun) notes.push('Singular only (a mass or abstract noun): the engine generates no plural.');
  if (!n.pluralOnly) {
    if (std === 'nb' && n.gender === 'f') notes.push(`Gender: feminine (ei ${n.lemma}); ${std2} also accepts the masculine paradigm (en ${n.lemma}, ${dfSg.find((d) => d.gender === 'Masc')?.form ?? 'the -en form'}), so the definite singular has two cells with the same features: ${dfSg.map((d) => d.form).join(' and ')}.`);
    else notes.push(`Gender: ${GENDER_WORD[n.gender]}.`);
  }
  if (n.gender === 'n' && n.plural.includes(n.lemma) && std === 'nb' && n.defPl.some((x) => /a$/.test(x))) notes.push('A one-syllable neuter has two definite plurals (husene, husa); both are cells.');
  notes.push('The genitive is the form + -s (bilens, husets): a spelling rule, not a cell of the table.');
  const template = n.pluralOnly ? 'plural-only noun' : n.massNoun ? `${GENDER_WORD[n.gender].split(' ')[0]} noun, no plural` : std === 'nb' && n.gender === 'f' ? 'feminine noun (ei / en)' : `${GENDER_WORD[n.gender].split(' ')[0]} noun`;
  return { cells, notes, template };
}

function nounParadigm(lex: NoLexicon, std: NoStandard, lemma: string): GeneratedParadigm | undefined {
  const n = lex.noun(lemma) ?? lex.noun(lc(lemma));
  if (n && !n.proper) {
    const g = nounCells(n, std);
    const notes = [`${STD_NAME[std]} (${std}) noun table.`, ...g.notes];
    if (n.unverified) notes.push('The author marks a plural or definite form of this row as unsure (unverified).');
    notes.push(NO_DICTIONARY);
    return { kind: 'noun-declension', cells: g.cells, layout: nounLayout(), template: `${STD_NAME[std]} ${g.template}`, notes };
  }
  if (n || lex.hasLemma(lemma) || lex.hasLemma(lc(lemma))) return undefined;
  // the engine's compound path: an unknown noun whose HEAD is a word-list noun inflects like the head
  const written = lc(lemma);
  const d = decomposeCompound(written, lex);
  if (!d || lc(d.headForm) !== lc(d.headLemma)) return undefined;
  const head = lex.noun(d.headLemma);
  if (!head || head.proper) return undefined;
  const g = nounCells(head, std);
  const cells = g.cells.map((c) => ({ features: c.features, form: d.prefix + c.form, ...(c.note ? { note: c.note.replaceAll(head.lemma, written) } : {}) }));
  const notes = [
    `${STD_NAME[std]} (${std}) noun table.`,
    `Guessed: ${written} is not in the word list; the engine reads it as a compound (${d.parts.filter((p) => p.kind !== 'link').map((p) => p.text).join(' + ')}${d.fuge.length ? `, linking -${d.fuge.join('-')}-` : ''}) and the head ${head.lemma} decides gender and inflection. Unconfirmed: check the forms against a dictionary.`,
    ...g.notes.map((x) => x.replaceAll(head.lemma, written)),
    NO_DICTIONARY,
  ];
  return { kind: 'noun-declension', cells, layout: nounLayout(), template: `${STD_NAME[std]} ${g.template} (guessed compound)`, notes };
}

// ───────────────────────── adjectives ─────────────────────────

const ADJ_LAYOUT: ParadigmLayout = {
  columns: { key: 'Gender', values: [['Fem,Masc', 'masculine / feminine (en, ei)'], ['Fem', 'feminine (only where it has its own form)'], ['Masc', 'masculine'], ['Neut', 'neuter (et)'], ['', 'every gender']] },
  rows: { key: 'Definite', values: [['Ind', 'indefinite (en stor bil)'], ['Def', 'definite singular (den store bilen)'], ['', 'plural, or one form (de store bilene)']] },
  sections: ['Degree'],
  labels: { Degree: { Pos: 'positive', Cmp: 'comparative (-ere / -are, or mer + adjective)', Sup: 'superlative (-est / -ast, or mest + adjective)' } },
};

function adjectiveCells(a: NoAdjective): { cells: Cell[]; notes: string[] } {
  const cells: Cell[] = [];
  const notes: string[] = [];
  const pos = (f: Features, form: string, note?: string): void => { cells.push({ features: { Degree: 'Pos', ...f }, form, ...(note ? { note } : {}) }); };
  pos({ Definite: 'Ind', Gender: 'Fem,Masc', Number: 'Sing' }, a.lemma);
  for (const f of a.feminine ?? []) pos({ Definite: 'Ind', Gender: 'Fem', Number: 'Sing' }, f, 'the feminine form (liten, lita): the common form above is the masculine');
  for (const f of a.neuter) pos({ Definite: 'Ind', Gender: 'Neut', Number: 'Sing' }, f);
  // the definite singular and the plural share the word list's one "plural and definite" list
  const shared = a.plural.length > 1 ? 'the word list gives one list for the definite singular and the plural and does not say which form is which' : undefined;
  for (const f of a.plural) pos({ Definite: 'Def', Number: 'Sing' }, f, shared);
  for (const f of a.plural) pos({ Number: 'Plur' }, f, shared);
  for (const f of a.comparative) cells.push({ features: { Degree: 'Cmp' }, form: f });
  for (const f of a.superlative) cells.push({ features: { Degree: 'Sup', Definite: 'Ind' }, form: f });
  for (const f of a.superlativeDef) cells.push({ features: { Degree: 'Sup', Definite: 'Def' }, form: f });
  if (a.invariable) notes.push('Invariable: the same form in every cell, and no comparison.');
  if (a.periphrastic) notes.push('Compared with mer and mest before the adjective (mer interessant, mest interessant), not with endings: there are no comparative or superlative cells.');
  if (a.feminine) notes.push('A separate feminine (lita) exists beside the common form (liten).');
  if (a.plural.length > 1) notes.push(`This adjective has different definite singular and plural forms (${a.plural.join(', ')}), but the engine keeps them in one list: every form is offered in both cells, and only a dictionary table can say which belongs where.`);
  else notes.push('The definite singular (after den / det) and the plural are the same form; both are cells so that a dictionary table can confirm each.');
  return { cells, notes };
}

function adjectiveParadigm(lex: NoLexicon, std: NoStandard, lemma: string): GeneratedParadigm | undefined {
  const a = lex.adjective(lemma) ?? lex.adjective(lc(lemma));
  if (a) {
    const g = adjectiveCells(a);
    const notes = [`${STD_NAME[std]} (${std}) adjective table.`, ...g.notes];
    if (a.unverified) notes.push('The author marks a form of this row as unsure (unverified).');
    notes.push(NO_DICTIONARY);
    return {
      kind: 'adjective-declension', cells: g.cells, layout: ADJ_LAYOUT,
      template: `${STD_NAME[std]} ${a.invariable ? 'invariable adjective' : a.periphrastic ? 'adjective compared with mer / mest' : 'adjective'}`, notes,
    };
  }
  return closedParadigm(lex, std, lemma, 'ADJ');
}

// ───────────────────────── verbs ─────────────────────────

function verbLayout(std: NoStandard): ParadigmLayout {
  return {
    columns: { key: 'Tense', values: [['Pres', 'present'], ['Past', 'past'], ['', 'no tense']] },
    rows: { key: 'VerbForm', values: [['Inf', 'infinitive (å ...)'], ['Fin', 'finite forms and the command'], ['Part', 'participle'], ['', 'the -s form']] },
    sections: ['Voice'],
    labels: { Voice: { '': 'active', Pass: std === 'nb' ? 'passive in -s (leses, finnes)' : 'passive in -st (lesast, finnast)' } },
  };
}

function verbCells(v: NoVerb): Cell[] {
  const cells: Cell[] = [];
  for (const f of v.infinitives) cells.push({ features: { VerbForm: 'Inf' }, form: f });
  for (const f of v.present) cells.push({ features: { VerbForm: 'Fin', Mood: 'Ind', Tense: 'Pres' }, form: f });
  for (const f of v.past) cells.push({ features: { VerbForm: 'Fin', Mood: 'Ind', Tense: 'Past' }, form: f });
  for (const f of v.supine) cells.push({ features: { VerbForm: 'Part', Tense: 'Past' }, form: f });
  for (const f of v.imperative) cells.push({ features: { VerbForm: 'Fin', Mood: 'Imp' }, form: f });
  for (const f of v.passive) cells.push({ features: { Voice: 'Pass' }, form: f });
  return cells;
}

function classTemplate(v: NoVerb, std: NoStandard): string {
  if (v.deponent) return 'deponent -s verb';
  if (std === 'nb') {
    return ({ '1': 'weak verb, class 1 (-et / -a)', '2': 'weak verb, class 2 (-te, -t)', '3': 'weak verb, class 3 (-de, -d)', '4': 'weak verb, class 4 (-dde, -dd)', s: 'strong or irregular verb (the word list gives the parts)' } as Record<string, string>)[v.cls] ?? 'verb';
  }
  return ({ a: 'a-verb (-ar, -a, -a)', e: 'e-verb (-er, -te, -t)', '1': 'weak verb', s: 'strong or irregular verb (the word list gives the parts)' } as Record<string, string>)[v.cls] ?? 'verb';
}

function verbParadigmOf(v: NoVerb, std: NoStandard): GeneratedParadigm {
  const notes = [`${STD_NAME[std]} (${std}) verb table.`];
  const irregular = v.cls === 's';
  if (irregular) notes.push('Strong or irregular verb: the past and the perfect participle come from the word list (not from a rule), so the vowel change is listed, not predicted.');
  if (v.deponent) notes.push(`${v.lemma} is a deponent -s verb: its -s form is the dictionary form, so the table has no separate active infinitive, command or -s passive.`);
  else if (!v.passive.length) notes.push('No -s passive is generated for this verb (a verb ending in a stressed vowel has none in the engine).');
  if (v.reflexive) notes.push(`Reflexive verb: used with seg (${v.lemma} seg); the cells are the forms of ${v.lemma} without the pronoun.`);
  if (std === 'nb' && (v.past.length > 1 || v.supine.length > 1)) notes.push('Two forms are accepted (-et and -a for a class-1 verb): both are cells with the same features.');
  if (std === 'nn' && v.infinitives.length > 1) notes.push('Nynorsk allows an infinitive in -e and in -a (kaste, kasta): both are cells.');
  notes.push('The perfect (har + participle), the future and the modal use (vil, skal, kan + infinitive) and the bli-passive (blir + participle) are constructions, not inflected words: they are listed under constructions, not in the table.');
  notes.push('Not generated: the present participle (-ende) and the participle used as an adjective (stengt, stengte).');
  if (v.unverified) notes.push('The author marks at least one form of this row as unsure (unverified).');
  notes.push(NO_DICTIONARY);
  return { kind: 'verb-conjugation', cells: verbCells(v), layout: verbLayout(std), template: `${STD_NAME[std]} ${classTemplate(v, std)}`, notes, constructions: [...VERB_CONSTRUCTIONS] };
}

function verbParadigm(lex: NoLexicon, std: NoStandard, lemma: string): GeneratedParadigm | undefined {
  const v = lex.verb(lemma) ?? lex.verb(lc(lemma)) ?? lex.verbs.find((x) => x.infinitives.includes(lc(lemma)));
  if (v) return verbParadigmOf(v, std);
  return auxParadigm(lex, std, lemma);
}

/** The auxiliaries (være, ha, bli, the modals) live in the closed-class word list, with every form written out. */
function auxParadigm(lex: NoLexicon, std: NoStandard, lemma: string): GeneratedParadigm | undefined {
  const ws = wordsOf(lex, lemma, 'AUX');
  if (!ws.length) return undefined;
  const cells: Cell[] = [];
  const order = (f: Features): number => (f.VerbForm === 'Inf' ? 0 : f.Tense === 'Pres' && f.VerbForm === 'Fin' ? 1 : f.Tense === 'Past' && f.VerbForm === 'Fin' ? 2 : f.VerbForm === 'Part' ? 3 : 4);
  const seen = new Set<string>();
  for (const w of ws) {
    for (const features of norwegianCellFeatures('AUX', w.morph)) {
      const key = `${JSON.stringify(Object.entries(features).sort())}|${w.form}`;
      if (seen.has(key)) continue;
      seen.add(key);
      const note = [w.register?.length ? w.register.join(', ') : '', w.unverified ? 'unverified (the author is unsure of this form)' : ''].filter(Boolean).join('; ');
      cells.push({ features, form: w.form, ...(note ? { note } : {}) });
    }
  }
  cells.sort((a, b) => order(a.features) - order(b.features));
  const notes = [
    `${STD_NAME[std]} (${std}) auxiliary table, from the closed-class word list.`,
    'An auxiliary has no -s passive or imperative cell unless the word list gives the form (være has vær; ha has ha).',
    'The perfect (har + participle), the future and the modal use (vil, skal, kan + infinitive) and the bli-passive (blir + participle) are constructions, not inflected words: they are listed under constructions, not in the table.',
    NO_DICTIONARY,
  ];
  return { kind: 'verb-conjugation', cells, layout: verbLayout(std), template: `${STD_NAME[std]} auxiliary verb`, notes, constructions: [...VERB_CONSTRUCTIONS] };
}

// ───────────────────────── pronouns, determiners and the word-list adjectives ─────────────────────────

function wordsOf(lex: NoLexicon, lemma: string, pos: PartOfSpeech): NoWordForm[] {
  const l = lc(lemma);
  return lex.words.filter((w) => lc(w.lemma) === l && w.pos === pos);
}

const PRON_LAYOUT: ParadigmLayout = {
  columns: { key: 'Case', values: [['Nom', 'subject (jeg, han)'], ['Acc', 'object (meg, ham)'], ['', 'one form']] },
  rows: { key: 'Gender', values: [['Masc', 'masculine'], ['Fem', 'feminine'], ['Neut', 'neuter'], ['', 'no gender']] },
  sections: ['Person', 'Number'],
  labels: { Person: { '1': 'first person', '2': 'second person', '3': 'third person' }, Number: { Sing: 'singular', Plur: 'plural' } },
};
const DET_LAYOUT: ParadigmLayout = {
  columns: { key: 'Number', values: [['Sing', 'singular'], ['Plur', 'plural'], ['', 'no number']] },
  rows: { key: 'Gender', values: [['Fem,Masc', 'masculine / feminine (en, ei)'], ['Fem', 'feminine (ei)'], ['Masc', 'masculine'], ['Neut', 'neuter (et)'], ['', 'every gender']] },
  sections: ['Person', 'Definite'],
  labels: { Person: { '1': 'owner: first person', '2': 'owner: second person', '3': 'owner: third person' }, Definite: { Def: 'definite', Ind: 'indefinite' } },
};

const PRONTYPE: Record<string, string> = { Prs: 'personal pronoun', Dem: 'demonstrative', Art: 'article', Ind: 'indefinite', Tot: 'total (all, every)', Neg: 'negative', Int: 'interrogative', Rel: 'relative', Rcp: 'reciprocal' };

function closedParadigm(lex: NoLexicon, std: NoStandard, lemma: string, pos: 'PRON' | 'DET' | 'ADJ'): GeneratedParadigm | undefined {
  const ws = wordsOf(lex, lemma, pos);
  if (!ws.length) return undefined;
  const cells: Cell[] = [];
  const seen = new Set<string>();
  for (const w of ws) {
    const features = pos === 'ADJ' ? norwegianCellFeatures('ADJ', closedCellFeatures({ Degree: 'Pos', ...w.morph }))[0] ?? closedCellFeatures({ Degree: 'Pos', ...w.morph }) : closedCellFeatures(w.morph);
    const key = `${JSON.stringify(Object.entries(features).sort())}|${w.form}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const note = [w.register?.length ? w.register.join(', ') : '', w.unverified ? 'unverified (the author is unsure of this form)' : ''].filter(Boolean).join('; ');
    cells.push({ features, form: w.form, ...(note ? { note } : {}) });
  }
  const distinct = new Set(cells.map((c) => JSON.stringify(Object.entries(c.features).sort())));
  if (distinct.size < 2) return undefined; // one form: nothing to tabulate
  const m0 = ws[0].morph;
  const kind = m0.Poss === 'Yes' ? 'possessive' : PRONTYPE[m0.PronType] ?? '';
  const notes = [`${STD_NAME[std]} (${std}) ${pos === 'PRON' ? 'pronoun' : pos === 'DET' ? 'determiner' : 'adjective'} table, from the closed-class word list.`];
  if (m0.Poss === 'Yes') notes.push('A possessive agrees with the thing owned (min bil, mi bok, mitt hus, mine hus), not with the owner; the person in the section title is the owner.');
  notes.push('Only the forms the word list holds are cells; a missing cell is a gap in the list, not a claim that the form does not exist.');
  notes.push(NO_DICTIONARY);
  const layout = pos === 'PRON' ? PRON_LAYOUT : pos === 'DET' ? DET_LAYOUT : ADJ_LAYOUT;
  const k = pos === 'PRON' ? 'pronoun-paradigm' : pos === 'DET' ? 'determiner-paradigm' : 'adjective-declension';
  return { kind: k, cells, layout, template: `${STD_NAME[std]} ${kind && !/pronoun$/.test(kind) ? `${kind} ` : ''}${kind && /pronoun$/.test(kind) ? kind : pos === 'PRON' ? 'pronoun' : pos === 'DET' ? 'determiner' : 'adjective'}`, notes };
}

