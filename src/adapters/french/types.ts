/**
 * The French adapter's shared contract (docs/french/PLAN.md): the types every module of `src/adapters/french` builds
 * against, and the conventions that must hold across them. Nothing here is language data.
 *
 * FEATURES (the same keys and values the Spanish adapter and the dictionary mapping use, so that a rule reading and a
 * dictionary reading of one form never contradict each other; they are also the Universal Dependencies names):
 *   VerbForm  Fin | Inf | Part            (participe présent = Part + Tense Pres; participe passé = Part + Tense Past)
 *   Mood      Ind | Sub | Cnd | Imp       (the conditionnel is Mood Cnd + Tense Pres; an imperative carries no Tense)
 *   Tense     Pres | Imp | Past | Fut     (Imp = imparfait; Past = passé simple on a finite verb)
 *   Person    1 | 2 | 3      Number  Sing | Plur      Gender  Masc | Fem
 *   Definite  Def | Ind      PronType  Art | Prs | Dem | Rel | Int | Ind | Neg | Part (partitive article)
 *   Poss Yes   Reflex Yes   Polarity Neg   Case Nom | Acc | Dat (clitic pronouns only)   NumType Card | Ord
 * A value that is a union is a comma list in alphabetical order ("Fem,Masc"; "1,3"), as `morph()` in ../shared makes it.
 *
 * TOKENS (french/tokenize.ts decides them; every other module relies on this):
 *   - An elided word is its own token and keeps its apostrophe: l'homme → "l'" + "homme"; qu'il → "qu'" + "il".
 *     Its `normalized` always ends in the straight apostrophe U+0027 whatever the page wrote (’ ʼ ‘ ′ `), so a typographic
 *     apostrophe never makes a second vocabulary identity. The surface is the page's own text, untouched.
 *   - Lexical words that contain an apostrophe stay whole: aujourd'hui, quelqu'un, presqu'île, prud'homme …
 *   - A hyphenated compound is one token (peut-être, c'est-à-dire, grand-mère, quatre-vingt-dix).
 *   - A pronoun or `ce`, `là`, `ci` joined to a verb or noun by a hyphen is its own token WITHOUT the hyphen; the hyphen is a
 *     non-word token between them: donne-le-moi → donne · - · le · - · moi; a-t-il → a · - · t · - · il (the t is the euphonic t).
 *   - Every token slices the input exactly (surface === text.slice(start, end)).
 */
import type { PartOfSpeech, RegisterTag, WordPart } from '../../core';

/** One generated or listed form of a lexeme. */
export interface FrFormRec {
  form: string;
  morph: Record<string, string>;
  /** 'fr-hist' for an older spelling of the form, a region code for a regional one. */
  varieties?: string[];
  register?: RegisterTag[];
}

/** Every form of one verb, generated by french/verbs.ts. */
export interface FrConjugation {
  lemma: string;
  /** '1' = -er, '2' = -ir with -iss-, '3' = everything else (the traditional three groups). */
  group: '1' | '2' | '3';
  /** The auxiliary of the compound tenses. 'both' = être when intransitive / of movement, avoir when transitive (monter, sortir, passer …). */
  aux: 'avoir' | 'être' | 'both';
  /** True when the paradigm comes from the irregular tables or a listed model verb; false when it was derived from the ending alone. */
  listed: boolean;
  /** The model verb the paradigm follows, in plain words ("conjugated like prendre"). */
  model?: string;
  forms: FrFormRec[];
  /** Persons or tenses the verb does not have (falloir: third person singular only). */
  defective?: string;
}

/** One reading of a written form, from french/morphology.ts. Several can be right at once (porte: noun, or forms of porter). */
export interface FrenchAnalysis {
  lemma: string;
  pos: PartOfSpeech;
  morph: Record<string, string>;
  /** The halves of a contraction (au = à + le), or a verb with what is written onto it. Offsets within the form. */
  parts?: WordPart[];
  varieties?: string[];
  register?: RegisterTag[];
  /** In plain words, how the form was reached ("regular -er verb, passé simple, third person singular"). */
  rule: string;
  /** True when the lemma was confirmed by `knownLemma`; a rule-only reading stays at 0.6 or below. */
  lemmaKnown: boolean;
  confidence: number;
}

export interface FrAnalyzeOptions {
  /** Is this a real lemma (of this part of speech, when given)? Supplied by the adapter from its word list. Assumed to answer the same way each time. */
  knownLemma?: (lemma: string, pos?: PartOfSpeech) => boolean;
  /** The gender the word list gives a noun ('Masc' | 'Fem' | 'Fem,Masc'), when it has one. */
  genderOf?: (lemma: string, pos: PartOfSpeech) => string | undefined;
}

/** What the word list says about a lemma beyond its forms (french/entries.ts fills it from the row's tags). */
export interface FrAnnotation {
  varieties?: string[];
  register?: RegisterTag[];
  /** The word begins with an aspirated h: no elision and no liaison before it (le héros, les | héros). */
  hAspire?: boolean;
  /** A verb's auxiliary when it is not avoir. */
  aux?: 'être' | 'both';
  /** The verb is normally used with a reflexive pronoun (se souvenir). */
  pronominal?: boolean;
}

export const annotationKey = (lemma: string, pos: PartOfSpeech): string => `${lemma}|${pos}`;

/** The variety codes the adapter labels (french/varieties.ts defines them). */
export type FrVarietyCode = 'fr-FR' | 'fr-CA' | 'fr-BE' | 'fr-CH' | 'fr-africa' | 'fr-louisiana' | 'fr-hist';
