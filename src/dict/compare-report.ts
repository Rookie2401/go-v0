/**
 * Renders the comparison (src/dict/compare.ts) as the committed Markdown report and the review JSON. Pure: same input,
 * byte-identical output (no clock; the only date in either file is the one inside the dictionary id).
 */
import type { SourceDisagreement } from '../core';
import { KAIKKI_ATTRIBUTION, KAIKKI_LICENCE } from './build';
import {
  COMPARE_SCHEMA, KIND_ORDER, POS_COMPATIBLE, countByKind,
  type CompareResult, type CorpusCoverageRow, type DictStats, type DisagreementKind,
} from './compare';

export interface SourceFileInfo {
  file: string;
  bytes?: number;
  lines?: number;
  sha256?: string;
  lastModified?: string;
  url?: string;
}

export interface ReportInput {
  result: CompareResult;
  dictStats: DictStats;
  source: SourceFileInfo;
  corpus: { rows: CorpusCoverageRow[]; total: CorpusCoverageRow };
  resolutionProblems?: string[];
}

const pct = (n: number, d: number): string => (d ? `${((100 * n) / d).toFixed(1)} %` : 'n/a');
const num = (n: number): string => n.toLocaleString('en-US');
const cell = (s: string): string => s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

const KIND_TITLE: Record<DisagreementKind, string> = {
  'missing': 'missing (the dictionary has no entry)',
  'part-of-speech': 'part of speech',
  'meaning': 'meaning',
  'register': 'register',
  'classifier': 'classifier',
  'tone': 'tone (exception and settled lists)',
  'syllables': 'syllables (exception and settled lists)',
  'pronunciation': 'pronunciation (respelling and hand romanization)',
  'segmentation': 'segmentation',
  'gender': 'gender',
  'variety': 'variety',
  'inflection': 'inflection',
};

const CAN_SHOW: Record<DisagreementKind, string> = {
  'missing': 'Can show: the dictionary file has no entry the mapper could read for that written form. Cannot show: that the hand entry is at fault, or that the word is not Thai; Wiktionary may list the word under another spelling or lack it.',
  'part-of-speech': 'Can show: the hand part of speech and the dictionary\'s share no kind of word even under the equivalence table below. Cannot show which is right; the two tag sets divide Thai words differently, and Wiktionary lines whose part of speech the mapper does not read are not counted.',
  'meaning': 'Can show: no content word of the hand gloss turns up in any gloss of the form. Cannot show: that the meanings differ. A synonym, a paraphrase or a narrower sense looks the same to this test. The dictionary side is the capped short view the mapper keeps (the first gloss of each sense).',
  'register': 'Can show: a register tag on one side that the other side\'s labels lack or differ from. Cannot show a mistake: Wiktionary labels sparingly and labels single senses, so an unlabelled entry is weak evidence. Only labels the dictionary actually uses are compared; the course\'s royal, religious, regional and child-directed tags have no counterpart there.',
  'classifier': 'Can show: the dictionary neither files the form as a classifier nor lists it as a classifier of any noun. Cannot show that it is not used as one.',
  'tone': 'Can show: the tones the engine reads from a course respelling differ from every listed IPA reading with the same number of syllables. Cannot show which reading is right, and says nothing about words outside the two exception lists.',
  'syllables': 'Can show: the syllable count of a course respelling matches no listed reading. Cannot show which division is right.',
  'pronunciation': 'Can show: a course respelling or romanization that is written differently from every listed one. Different systems and conventions produce such differences with identical sound; a romanization is compared only through a coarse skeleton that ignores tone.',
  'segmentation': 'Not produced by this comparison (see docs/thai/BENCHMARKS.md).',
  'gender': 'Not produced by the Thai comparison.',
  'variety': 'Not produced by the Thai comparison.',
  'inflection': 'Not produced by the Thai comparison.',
};

function table(head: string[], rows: string[][], textColumns = 1): string {
  return [`| ${head.join(' | ')} |`, `| ${head.map((_, i) => (i < textColumns ? '---' : '---:')).join(' | ')} |`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');
}

export function renderReport(input: ReportInput): string {
  const { result: r, dictStats: ds, source, corpus } = input;
  const L: string[] = [];
  const counts = countByKind(r.disagreements);
  const total = r.disagreements.length;
  const open = r.disagreements.filter((d) => d.status === 'open').length;

  L.push(`# Thai hand data against the dictionary (${r.dictionaryId})`, '');
  L.push(`Dictionary data below is from ${KAIKKI_ATTRIBUTION}. Licence: ${KAIKKI_LICENCE}. Words and short readings are quoted here as findings; the dictionary itself is not copied into the repository.`, '');
  L.push('Generated by `npm run dict:compare` (src/dict/compare.ts); do not edit by hand. The full list of disagreements is `data/review/th/disagreements.json`; decisions go in `data/review/th/resolutions.json`.', '');
  L.push('The hand data (word list, phrase units, constructions, tone exception lists) is machine-drafted and not native-reviewed. The dictionary is a separately sourced layer. **Where the two differ neither is chosen: the difference is recorded for a human reviewer.** A record means "possibly different", never "wrong".', '');

  L.push('## Source', '');
  L.push(`- dictionary id: \`${r.dictionaryId}\``);
  L.push(`- file: \`${source.file}\`${source.url ? ` (${source.url})` : ''}`);
  if (source.lastModified) L.push(`- source last modified: ${source.lastModified}`);
  if (source.bytes !== undefined) L.push(`- size: ${num(source.bytes)} bytes, ${num(source.lines ?? ds.lines)} lines${source.sha256 ? `, sha256 \`${source.sha256}\`` : ''}`);
  L.push(`- read by the dictionary mapper: ${num(ds.entries)} entries from ${num(ds.lines - ds.noEntry - ds.malformed)} lines (${num(ds.noEntry)} lines gave no entry, ${num(ds.malformed)} malformed); ${num(ds.forms)} distinct forms`);
  L.push(`- hand data: ${num(r.handCounts.entries)} lexicon entries (${num(r.handCounts.distinctForms)} distinct forms), ${num(r.handCounts.phrases)} phrase units, ${num(r.handCounts.compounds)} course compounds, ${num(r.handCounts.exceptions)} irregular words and ${num(r.handCounts.settled)} settled words in the tone exception lists`, '');

  L.push('## Coverage of the hand entries', '');
  L.push('How many hand entries the dictionary has. "Form" is the written form only. "Form + part of speech" needs an entry of the same part of speech; "or equivalent" also accepts the usual differences between the two tag sets (table at the end). A form that is absent is recorded as a `missing` disagreement, which is a fact about coverage, not a finding against either source.', '');
  L.push(table(['group', 'entries', 'distinct forms', 'by form', 'form + POS (exact)', 'form + POS (or equivalent)'],
    r.coverage.map((c) => [
      c.label, num(c.total), num(c.distinctForms), `${num(c.byForm)} (${pct(c.byForm, c.total)})`,
      c.byFormPos === undefined ? '-' : `${num(c.byFormPos)} (${pct(c.byFormPos, c.total)})`,
      c.byFormPosCompatible === undefined ? '-' : `${num(c.byFormPosCompatible)} (${pct(c.byFormPosCompatible, c.total)})`,
    ])), '');
  L.push('Groups: *classifiers* are entries with part of speech CLF or listed in classifiers.ts; *function words* are the entries of function-words.ts and any entry with a role (particles, markers, connectives, pronouns); *core vocabulary* is the rest (the seed list in th.ts and lexicon-core.ts). *Phrase units* and *course compounds* are counted as headwords, by form only.', '');

  L.push('## Disagreements by kind', '');
  L.push(table(['kind', 'open', 'resolved'], [...counts.map((c) => [c.kind, num(c.open), num(c.resolved)]), ['all', num(open), num(total - open)]]), '');
  L.push('Comparisons actually made (a kind with no disagreement is only meaningful next to how many were made):', '');
  const CHECKED: Array<[string, string]> = [
    ['partOfSpeechChecked', 'hand entries whose form has a dictionary entry with a usable part of speech'],
    ['meaningChecked', 'hand glosses with a content word, compared with the glosses of the form'],
    ['registerChecked', 'hand register tags the dictionary has a label for'],
    ['classifierChecked', 'hand classifier entries found in the dictionary'],
    ['romanizationChecked', 'hand romanizations compared with a listed romanization'],
    ['syllablesChecked', 'exception-list words compared by syllable count'],
    ['toneChecked', 'exception-list words compared by tone'],
    ['respellingChecked', 'exception-list words compared by respelling'],
  ];
  for (const [k, why] of CHECKED) L.push(`- ${num(r.checked[k] ?? 0)}: ${why}`);
  L.push('');
  if (Object.keys(r.notComparable).length) {
    L.push('Comparisons that could not be made (not counted above):', '');
    for (const [why, n] of Object.entries(r.notComparable).sort(([a], [b]) => (a < b ? -1 : 1))) L.push(`- ${num(n)}: ${why}`);
    L.push('');
  }
  if (r.staleResolutions.length) L.push(`Resolutions whose id matches no current disagreement (kept in resolutions.json): ${r.staleResolutions.length}.`, '');
  if (input.resolutionProblems?.length) L.push('Entries of resolutions.json that could not be read:', '', ...input.resolutionProblems.map((p) => `- ${p}`), '');

  L.push('## Pronunciation coverage', '');
  const p = r.pronunciation;
  L.push('Dictionary forms (distinct written forms the mapper produced) and hand forms with a respelling, an IPA reading and a romanization:', '');
  L.push(table(['', 'forms', 'respelling', 'IPA', 'romanization', 'any'], [
    ['dictionary', num(p.dictionary.forms), `${num(p.dictionary.withRespelling)} (${pct(p.dictionary.withRespelling, p.dictionary.forms)})`, `${num(p.dictionary.withIpa)} (${pct(p.dictionary.withIpa, p.dictionary.forms)})`, `${num(p.dictionary.withRomanization)} (${pct(p.dictionary.withRomanization, p.dictionary.forms)})`, `${num(p.dictionary.withAny)} (${pct(p.dictionary.withAny, p.dictionary.forms)})`],
    ['hand forms found in the dictionary', num(p.hand.formsInDictionary), `${num(p.hand.dictRespelling)} (${pct(p.hand.dictRespelling, p.hand.formsInDictionary)})`, `${num(p.hand.dictIpa)} (${pct(p.hand.dictIpa, p.hand.formsInDictionary)})`, `${num(p.hand.dictRomanization)} (${pct(p.hand.dictRomanization, p.hand.formsInDictionary)})`, `${num(p.hand.dictAny)} (${pct(p.hand.dictAny, p.hand.formsInDictionary)})`],
  ]), '');
  L.push(`The hand lexicon itself carries a romanization for ${num(p.hand.withOwnRomanization)} of ${num(p.hand.entries)} entries (${pct(p.hand.withOwnRomanization, p.hand.entries)}); it has no tones and no IPA. For the other hand entries the pronunciation is worked out by the spelling rules at run time, or comes from the dictionary when one is installed.`, '');
  L.push('Word tokens of the Thai course documents under `data/corpus/th/` and of the synthetic test book, tokenized and analysed by the real adapter. "Hand" = the lexicon has an analysis; "dictionary" = the dictionary has an entry for the form; "dictionary pronunciation" = that entry carries a respelling, IPA or romanization; "neither" = no hand analysis and no dictionary entry. These texts are small and course-authored: they say how well the two sources cover the course, not Thai in general.', '');
  const corpusRow = (c: CorpusCoverageRow) => [c.name, num(c.tokens), num(c.types), `${num(c.withHand)} (${pct(c.withHand, c.tokens)})`, `${num(c.withDictionary)} (${pct(c.withDictionary, c.tokens)})`, `${num(c.withDictionaryPronunciation)} (${pct(c.withDictionaryPronunciation, c.tokens)})`, `${num(c.neither)} (${pct(c.neither, c.tokens)})`];
  L.push(table(['document', 'tokens', 'types', 'hand', 'dictionary', 'dictionary pronunciation', 'neither'], [...corpus.rows.map(corpusRow), corpusRow(corpus.total)]), '');

  L.push('## What each comparison can and cannot show', '');
  for (const k of KIND_ORDER) if (k !== 'segmentation') L.push(`- **${KIND_TITLE[k]}.** ${CAN_SHOW[k]}`);
  L.push('', 'All of them compare the hand data with the dictionary as the mapper reads it. A line the mapper skips, a gloss it truncates or a label it does not map is invisible here.', '');

  L.push('## First 40 of each kind', '');
  L.push('Sorted by form in code-unit order. The full list is `data/review/th/disagreements.json`.', '');
  for (const k of KIND_ORDER) {
    const list = r.disagreements.filter((d) => d.field === k);
    if (!list.length) continue;
    L.push(`### ${KIND_TITLE[k]}: ${num(list.length)}`, '');
    L.push(table(['form', 'course', 'dictionary', 'status'], list.slice(0, 40).map((d: SourceDisagreement) => [d.form, d.ours.value, d.theirs.value, d.status]), 4), '');
  }

  L.push('## Method notes', '');
  L.push('Part-of-speech equivalence used (hand part of speech: dictionary parts of speech accepted as the same kind of word):', '');
  for (const [pos, ok] of Object.entries(POS_COMPATIBLE)) if (pos !== 'X' && pos !== 'PUNCT') L.push(`- ${pos}: ${ok.join(', ')}`);
  L.push('', `Register labels the dictionary uses often enough (at least 5 entries) to be compared: ${r.method.registerVocabulary.join(', ') || '(none)'}. Strong labels checked in the other direction: ${r.method.strongLabels.join(', ')}.`, '');
  L.push('Dictionary entries by part of speech as the mapper reads them:', '');
  L.push(Object.entries(ds.posCounts).sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1)).map(([k, n]) => `${k} ${num(n)}`).join(', '), '');
  L.push(`Classifier headwords the dictionary lists (as a classifier entry or in some noun's classifier list): ${num(ds.classifierForms.size)}.`, '');
  return `${L.join('\n')}\n`;
}

/** The review file: every disagreement (open and resolved), deterministic order, with the attribution beside the dictionary's words. */
export function renderDisagreementsJson(input: ReportInput): string {
  const { result: r, source } = input;
  const out = {
    schema: COMPARE_SCHEMA,
    note: 'Possible differences between the machine-drafted Thai hand data and the dictionary, recorded for a human reviewer. Neither side is chosen. Decisions belong in resolutions.json, keyed by id. Generated by npm run dict:compare.',
    attribution: `Dictionary data: ${KAIKKI_ATTRIBUTION}. Licence: ${KAIKKI_LICENCE}.`,
    dictionary: { id: r.dictionaryId, file: source.file, sha256: source.sha256, lastModified: source.lastModified },
    counts: Object.fromEntries(countByKind(r.disagreements).map((c) => [c.kind, { open: c.open, resolved: c.resolved }])),
    disagreements: r.disagreements,
  };
  return `${JSON.stringify(out, null, 2)}\n`;
}
