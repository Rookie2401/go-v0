<#
.SYNOPSIS
  Set up a NAMED Cloudflare tunnel from this PC to the local Go Repository service (http://127.0.0.1:8790), on the owner's
  own domain, so the phone (GoReview on TestFlight / the PWA) and the desktop share one address that never changes.

.DESCRIPTION
  A quick tunnel (cloudflared tunnel --url …) has no uptime guarantee and gets a new *.trycloudflare.com name every start,
  which strands the phone's queued events under the old address. A named tunnel is tied to a DNS name on a zone the owner
  holds on Cloudflare and keeps that name across restarts and reboots (installed as a Windows service).

  Steps this script performs (idempotent; re-run safely):
    1. cert.pem check  — the one-time browser authorisation (`cloudflared tunnel login`). The script opens it and stops;
                         the OWNER signs in to Cloudflare in the browser and picks the zone. Nothing here enters credentials.
    2. tunnel create   — `cloudflared tunnel create <TunnelName>` (skipped when it exists); the credentials JSON lands in
                         %USERPROFILE%\.cloudflared\<tunnel-id>.json (never commit it).
    3. config.yml      — %USERPROFILE%\.cloudflared\config.yml with an ingress rule <Hostname> → http://127.0.0.1:<Port>
                         (the long-poll /sync/wait needs no special timeout: cloudflared's default is well above 25 s).
    4. DNS route       — `cloudflared tunnel route dns <TunnelName> <Hostname>` (a CNAME to <tunnel-id>.cfargotunnel.com).
    5. service install — `cloudflared service install` so the tunnel starts with Windows (needs an elevated prompt); without
                         elevation it prints the command to run and offers `cloudflared tunnel run` for a foreground test.
    6. verify          — GET https://<Hostname>/health must report ok:true, service "repository", contractVersion 3.

.PARAMETER Hostname   The public name to use, on a zone in the owner's Cloudflare account, e.g. repo.example.com
.PARAMETER TunnelName Name of the tunnel (default goreview-repository)
.PARAMETER Port       Local service port (default 8790)
.PARAMETER Cloudflared Path to cloudflared.exe (default: the copy Codex placed under Documents\Codex\…\work\tools, else PATH)

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File infra\cloudflare\setup-named-tunnel.ps1 -Hostname repo.example.com
#>
param(
  [Parameter(Mandatory = $true)][string]$Hostname,
  [string]$TunnelName = 'goreview-repository',
  [int]$Port = 8790,
  [string]$Cloudflared = ''
)

$ErrorActionPreference = 'Stop'

function Find-Cloudflared {
  param([string]$Given)
  if ($Given -and (Test-Path $Given)) { return (Resolve-Path $Given).Path }
  $codex = Join-Path $env:USERPROFILE 'Documents\Codex\2026-10-14\ple\work\tools\cloudflared.exe'
  if (Test-Path $codex) { return $codex }
  $cmd = Get-Command cloudflared -ErrorAction SilentlyContinue
  if ($cmd) { return $cmd.Source }
  throw "cloudflared.exe not found. Install it (winget install Cloudflare.cloudflared) or pass -Cloudflared <path>."
}

if ($Hostname -notmatch '^[a-z0-9.-]+\.[a-z]{2,}$') { throw "Hostname '$Hostname' is not a DNS name (e.g. repo.example.com)." }

$cf = Find-Cloudflared $Cloudflared
$cfHome = Join-Path $env:USERPROFILE '.cloudflared'
$cert = Join-Path $cfHome 'cert.pem'
$config = Join-Path $cfHome 'config.yml'
Write-Host "cloudflared: $cf"
Write-Host "tunnel: $TunnelName  hostname: $Hostname  local: http://127.0.0.1:$Port"

# 1. one-time authorisation (owner, in the browser)
if (-not (Test-Path $cert)) {
  Write-Host ''
  Write-Host 'No Cloudflare authorisation on this PC yet. A browser window will open: sign in to the Cloudflare account that'
  Write-Host "holds the zone for $Hostname and choose that zone. When it says the certificate was installed, re-run this script."
  & $cf tunnel login
  exit 2
}

# 2. the tunnel (idempotent)
$listJson = & $cf tunnel list --output json 2>$null
$tunnels = @()
if ($listJson) { try { $tunnels = $listJson | ConvertFrom-Json } catch { $tunnels = @() } }
$existing = $tunnels | Where-Object { $_.name -eq $TunnelName } | Select-Object -First 1
if ($existing) {
  $tunnelId = $existing.id
  Write-Host "tunnel '$TunnelName' exists: $tunnelId"
} else {
  Write-Host "creating tunnel '$TunnelName'…"
  & $cf tunnel create $TunnelName | Out-Host
  $listJson = & $cf tunnel list --output json
  $tunnelId = ($listJson | ConvertFrom-Json | Where-Object { $_.name -eq $TunnelName } | Select-Object -First 1).id
  if (-not $tunnelId) { throw 'The tunnel was not created.' }
  Write-Host "created: $tunnelId"
}
$credentials = Join-Path $cfHome "$tunnelId.json"
if (-not (Test-Path $credentials)) { throw "Credentials file missing: $credentials (create the tunnel on this PC, or copy the JSON here)." }

# 3. config.yml (the ingress; the catch-all 404 is required by cloudflared)
$yaml = @"
# Named tunnel for the Go Repository service (generated by infra/cloudflare/setup-named-tunnel.ps1). Keep out of git.
tunnel: $tunnelId
credentials-file: $credentials
protocol: quic
ingress:
  - hostname: $Hostname
    service: http://127.0.0.1:$Port
    originRequest:
      connectTimeout: 10s
      noTLSVerify: true
  - service: http_status:404
"@
New-Item -ItemType Directory -Force -Path $cfHome | Out-Null
Set-Content -Path $config -Value $yaml -Encoding utf8
Write-Host "wrote $config"
& $cf tunnel ingress validate | Out-Host

# 4. DNS route (idempotent: cloudflared refuses to overwrite a different record; it reports an existing matching one)
Write-Host "routing $Hostname → tunnel $TunnelName…"
try { & $cf tunnel route dns $TunnelName $Hostname | Out-Host } catch { Write-Host "route dns: $($_.Exception.Message)" }

# 5. run as a Windows service (elevated), else explain
$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
$svc = Get-Service -Name cloudflared -ErrorAction SilentlyContinue
if ($svc) {
  Write-Host "service 'cloudflared' is installed ($($svc.Status)); restarting it to pick up the config…"
  if ($isAdmin) { Restart-Service cloudflared } else { Write-Host 'Not elevated: run  Restart-Service cloudflared  from an administrator prompt.' }
} elseif ($isAdmin) {
  & $cf service install | Out-Host
  Start-Service cloudflared
  Write-Host "service 'cloudflared' installed and started"
} else {
  Write-Host ''
  Write-Host 'To start the tunnel with Windows, run from an ADMINISTRATOR PowerShell:'
  Write-Host "  & `"$cf`" service install"
  Write-Host '  Start-Service cloudflared'
  Write-Host 'For a foreground test right now (stops when the window closes):'
  Write-Host "  & `"$cf`" tunnel run $TunnelName"
}

# 6. verify through the public name (gives DNS a few seconds)
Write-Host ''
Write-Host "checking https://$Hostname/health …"
$ok = $false
for ($i = 0; $i -lt 12 -and -not $ok; $i++) {
  try {
    $r = Invoke-RestMethod -Uri "https://$Hostname/health" -TimeoutSec 10
    if ($r.ok -eq $true -and $r.service -eq 'repository') { $ok = $true; Write-Host ("health: ok, contractVersion {0}" -f $r.contractVersion) }
  } catch { Start-Sleep -Seconds 5 }
}
if (-not $ok) {
  Write-Host 'Not reachable yet. Checks: is the local service on the port (http://127.0.0.1:' + $Port + '/health)? is the tunnel running (service or `tunnel run`)? DNS can take a minute.'
  exit 3
}
Write-Host ''
Write-Host "Done. Use https://$Hostname as the Repository service address:"
Write-Host '  - GoReview PWA / hosted copy: config.json serviceUrl'
Write-Host '  - TestFlight build: REPOSITORY_SERVICE_URL for packages/goreview-ios release:stage (next build)'
Write-Host '  - GoLearn extension on this PC may keep http://127.0.0.1:8790 (same database)'
