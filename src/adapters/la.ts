/**
 * Latin adapter (reading target: the Clementine Vulgate and the Latin of the Church; Classical spellings and the Romance app's corpus
 * texts are read too). NFC + case + ligature + length-mark + j/i + u/v fold for identity; the written form is never changed.
 *
 * Layers, in the order a token meets them (docs/latin/ADAPTER.md):
 *   seed lexicon (latin/lexicon-data.ts: about 1,500 of the commonest Vulgate lemmas with their principal parts, from Whitaker's Words,
 *   ranked by Vulgate counts) + closed classes ported from the Romance app (latin/closed-data.ts: pronouns, the irregular verbs sum, possum,
 *   eo, fero, volo, nolo, malo, fio, numerals, prepositions, particles) + compounds of sum / eo / fero (latin/lexicon-extra.ts)
 *   → the word-form engine (latin/morph-*.ts: every cell of the five declensions, the adjectives in three degrees, the four conjugations
 *   with deponents, active and passive, every mood; latin/morphology.ts looks a written word up, splits -que / -ne / -ve, reads capital
 *   Roman numerals, and guesses an unknown word from its ending, marked unconfirmed)
 *   → the sentence layer (latin/sentence.ts: what a preposition governs, cum as preposition or conjunction)
 *   → constructions (ablative absolute, accusative + infinitive, cum / ut / ne clauses, gerund and gerundive, perfect passive, deponents)
 *   and a shallow dependency layer (latin/syntax.ts).
 * Confident: a word the seed lexicon or the closed tables hold, in any of its generated forms. Uncertain, and said so: a reading for a word
 * outside them (`unconfirmed`, 0.4 at most, no gloss), a name whose declension is assumed from its ending, a derived adverb, a union
 * the neighbours do not decide (Case "Acc,Nom", "Abl,Dat"). There is no parser. The data is machine-drafted and no Latinist has checked it.
 */
import type { AdapterSupport, AnalysisSourceInfo, LanguageAdapter, PronunciationSupport, RawToken } from '../core';
import { speechNormalizeGeneric } from './shared';
import { LA_ANALYZER_VERSION, LA_SOURCE_IDS } from './latin/version';
import { lookupKey, segmentLatinSentences, spellingVariants, tokenizeLatin } from './latin/orthography';
import { latinAnalyze } from './latin/sentence';
import { wordCandidates } from './latin/morphology';
import { describeLatinMorph } from './latin/describe';
import { detectLatinConstructions, detectLatinPhrases } from './latin/constructions';
import { latinCellsFor, latinParadigm } from './latin/paradigm';
import { latinFeaturesFromTableTags, latinMorphFromTags } from './latin/tags';
import { latinSyntax } from './latin/syntax';
import { latinPronunciation, latinNumberToWords } from './latin/pronunciation';
import { latinLexiconLoaded, loadLatinLexicon } from './latin/lexicon-load';

const LANG = 'la' as const;
const VERSION = LA_ANALYZER_VERSION;

export { LA_SOURCE_IDS, latinLexiconLoaded, loadLatinLexicon };

const SOURCES: Record<string, AnalysisSourceInfo> = {
  [LA_SOURCE_IDS.lexicon]: { id: LA_SOURCE_IDS.lexicon, label: "Seed word list (Whitaker's Words entries for the commonest Vulgate lemmas)", origin: 'dictionary', reviewStatus: 'external', licence: "Whitaker's Words: free for any use (William Whitaker); the kigawas/whitakers-words redistribution is MIT", version: VERSION },
  [LA_SOURCE_IDS.closed]: { id: LA_SOURCE_IDS.closed, label: 'Closed classes ported from the Romance app (pronouns, irregular verbs, numerals, prepositions, particles)', origin: 'hand', reviewStatus: 'machine-drafted', version: VERSION },
  [LA_SOURCE_IDS.rules]: { id: LA_SOURCE_IDS.rules, label: 'Latin word-form and guessing rules', origin: 'rule', reviewStatus: 'machine-drafted', version: VERSION },
  [LA_SOURCE_IDS.constructions]: { id: LA_SOURCE_IDS.constructions, label: 'Latin grammar patterns', origin: 'hand', reviewStatus: 'machine-drafted', version: VERSION },
  [LA_SOURCE_IDS.phrases]: { id: LA_SOURCE_IDS.phrases, label: 'Latin fixed phrases', origin: 'hand', reviewStatus: 'machine-drafted', version: VERSION },
  [LA_SOURCE_IDS.tags]: { id: LA_SOURCE_IDS.tags, label: 'Wiktionary Latin inflection-tag vocabulary (kaikki.org), for mapping a dictionary table to features', origin: 'dictionary', reviewStatus: 'external', licence: 'CC BY-SA 4.0 (Wiktionary)', version: VERSION },
};

const SUPPORT: AdapterSupport = {
  tokenization: 'dependable',
  sentenceSegmentation: 'limited',
  lemmatization: 'seed-only',
  morphology: 'limited',
  phraseDetection: 'limited',
  productionChecks: 'none',
  limitations: [
    'Lemmatization is seed-only: the word list is about 1,500 of the commonest lemmas of the Clementine Vulgate (with the closed classes and the compounds of sum, eo and fero) from Whitaker\'s Words, machine-drafted and not checked by a Latinist; a word outside it gets a reading the endings only suggest (marked unconfirmed, 0.4 at most, no gloss) or none.',
    'Forms are generated by rule from the principal parts: the five declensions, adjectives in three degrees, the four conjugations with deponents, in the active and passive and every mood. Irregular forms outside sum, possum, eo, fero, volo, nolo, malo, fio and the listed compounds are not generated (vis, bos, senex, iter, domus is listed, fas and the like are missing).',
    'The spelling is read through a fold (ae/oe ligatures, j/i, u/v, length marks): the text is never changed. Medieval spellings the fold does not cover (e for ae in a word the lexicon spells with ae is covered by lemmaVariants, other changes are not) get no reading.',
    'The sentence layer decides only what a preposition governs and cum as preposition or conjunction; everything else a form leaves open stays a union (Case "Abl,Dat", Mood "Ind,Sub"). There is no parser: the shallow dependency layer reads case endings and agreement, clause by clause between punctuation marks.',
    'Names: a name the word list does not hold in a declined form is assumed indeclinable or declined by its ending (rule-built, said in the notes); Hebrew names that decline in the Vulgate only in part are not modelled.',
    'Vowel length is not marked in the text and not analysed: forms that differ only in length (the perfect subjunctive and the future perfect, reg-it present and perfect) are listed as separate readings only where their spelling differs.',
    'No production checks (GoTell): none are written for Latin.',
  ],
};

const normalize = (s: string): string => lookupKey(s);

export const laAdapter: LanguageAdapter = {
  lang: LANG,
  name: 'Latin',
  script: 'Latn',
  version: VERSION,
  support: SUPPORT,
  sources: SOURCES,

  segmentSentences: segmentLatinSentences,
  tokenize: tokenizeLatin,
  normalize,
  searchNormalize: (q) => lookupKey(q).trim(),

  analyze: (tokens: RawToken[]) => latinAnalyze(tokens),

  detectPhrases: (tokens, analyses) => detectLatinPhrases(tokens, analyses),
  detectPatterns: (tokens, analyses) => detectLatinConstructions(tokens, analyses),

  pronunciation: (token): PronunciationSupport => latinPronunciation(token.surface),

  speechNormalize: (text) =>
    speechNormalizeGeneric(text, {
      tool: 'speech-la@1',
      numberToWords: latinNumberToWords,
      abbreviations: [
        { pattern: /\bcap\./gu, replacement: 'caput', label: 'cap.' },
        { pattern: /\bv\.\s?(?=\d)/gu, replacement: 'versus ', label: 'v.' },
      ],
    }),

  display: { wordSeparator: ' ', showBoundariesOnHighlight: false, fontFamily: 'Georgia, "Times New Roman", serif', lineHeight: 1.7 },

  checkProduction: () => [],

  relate: (a, b) => {
    const na = normalize(a);
    const nb = normalize(b);
    if (na === nb) return 'same';
    const la = new Set(wordCandidates(a).filter((c) => c.lemma && !c.unconfirmed).map((c) => c.lemma as string));
    for (const c of wordCandidates(b)) if (c.lemma && !c.unconfirmed && la.has(c.lemma)) return 'inflection';
    return 'none';
  },

  /** Linguistic Engine V2, Stage 4: shallow dependency relations (latin/syntax.ts). */
  syntax: (tokens, analyses) => latinSyntax(tokens, analyses),

  /** Other spellings a dictionary may file the lemma under: caelum / coelum, saeculum / seculum, Iesus / Jesus. */
  lemmaVariants: (lemma): string[] => spellingVariants(lemma).filter((v) => v !== lemma),

  morphFromTags: latinMorphFromTags,
  describeMorph: (morph, pos) => describeLatinMorph(morph, pos),

  /** Linguistic Engine V2, Stage 3: the generated paradigm (latin/paradigm.ts) and the dictionary's table tags in this adapter's feature keys (latin/tags.ts). */
  paradigm: latinParadigm,
  cellsFor: latinCellsFor,
  featuresFromTableTags: (tags, pos) => latinFeaturesFromTableTags(tags, pos),
};
